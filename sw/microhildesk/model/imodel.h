#pragma once

#include <cstdint>
#include <map>
#include <model/channel_state.h>
#include <sigc++/sigc++.h>
#include <string>
#include <string_view>

////////////////////////////////////////////////////////////////////////////////////////////////////////
/// @namespace Electux::App::Model
/// @brief Namespace for application data models and entities
namespace Electux::App::Model {
    ////////////////////////////////////////////////////////////////////////////////////////////////////
    /// @name Local Type Aliases
    /// @{
    using Entities = std::map<std::string, std::string, std::less<>>;
    using ChannelState = Electux::App::Model::Channel::ChannelState;
    /// @}
    ////////////////////////////////////////////////////////////////////////////////////////////////////

    ////////////////////////////////////////////////////////////////////////////////////////////////////
    /// @enum ModelControlKey
    /// @brief Defines valid configuration keys for the control system.
    ////////////////////////////////////////////////////////////////////////////////////////////////////
    enum class ModelControlKey : uint8_t {
        Enable = 0, ///< Key for enabling/disabling control features
        Mode,       ///< Key for setting the operational mode
        Toggle,     ///< Key for toggle-based control states
        Timer,      ///< Key for timer duration settings
        TimerEnable ///< Key for enabling/disabling timer functionality
    };

    ////////////////////////////////////////////////////////////////////////////////////////////////////
    /// @enum ModelLogKey
    /// @brief Defines valid configuration keys for the logging system.
    ////////////////////////////////////////////////////////////////////////////////////////////////////
    enum class ModelLogKey : uint8_t {
        FilePath = 0, ///< Key for the log file destination path
        LogLevel      ///< Key for the verbosity level setting
    };

    ////////////////////////////////////////////////////////////////////////////////////////////////////
    /// @enum ModelSerialKey
    /// @brief Defines valid configuration keys for serial communication.
    ////////////////////////////////////////////////////////////////////////////////////////////////////
    enum class ModelSerialKey : uint8_t {
        Device = 0, ///< Key for serial device path (e.g., /dev/ttyUSB0)
        Baud,       ///< Key for baud rate setting
        Data,       ///< Key for data bits setting
        Parity,     ///< Key for parity setting
        Stop,       ///< Key for stop bits setting
        Flow        ///< Key for flow control setting
    };

    ////////////////////////////////////////////////////////////////////////////////////////////////////
    /// @enum ModelGeneralKey
    /// @brief Defines valid configuration keys for general settings
    /// (communication mode, TCP).
    ////////////////////////////////////////////////////////////////////////////////////////////////////
    enum class ModelGeneralKey : uint8_t {
        ComType = 0, ///< Key for communication type ("serial" or "tcp")
        TcpIp,       ///< Key for TCP IP Address
        TcpPort      ///< Key for TCP Port
    };

    ////////////////////////////////////////////////////////////////////////////////////////////////////
    /// @enum ModelBleKey
    /// @brief Defines valid configuration keys for BLE settings.
    ////////////////////////////////////////////////////////////////////////////////////////////////////
    enum class ModelBleKey : uint8_t {
        Address = 0,       ///< BLE device address or name
        ServiceUuid,       ///< BLE service UUID
        RxUuid,            ///< BLE RX characteristic UUID
        TxUuid             ///< BLE TX characteristic UUID
    };

    ////////////////////////////////////////////////////////////////////////////////////////////////////
    /// @class IModel
    /// @brief Interface for application data models.
    ///
    /// Defines core operations for managing key-value pairs representing
    /// configuration or state data within the application.
    ////////////////////////////////////////////////////////////////////////////////////////////////////
    class IModel {
      public:
        ////////////////////////////////////////////////////////////////////////////////////////////////
        /// @brief Virtual destructor for the IModel interface.
        ////////////////////////////////////////////////////////////////////////////////////////////////
        inline virtual ~IModel() noexcept = default;

        ////////////////////////////////////////////////////////////////////////////////////////////////
        /// @brief Adds an entity to the model.
        /// @param key Represents the model entity key to be added.
        /// @param data Represents the model entity data to be added.
        /// @return true if the operation was successful, otherwise false.
        ////////////////////////////////////////////////////////////////////////////////////////////////
        virtual bool
        add(const std::string_view &key, const std::string_view &data) = 0;

        ////////////////////////////////////////////////////////////////////////////////////////////////
        /// @brief Validates if a string key is a valid control configuration
        /// key.
        /// @param key Represents the string key to be validated.
        /// @return true if the key is valid, false otherwise.
        ////////////////////////////////////////////////////////////////////////////////////////////////
        virtual bool validateKey(const std::string_view &key) const = 0;

        ////////////////////////////////////////////////////////////////////////////////////////////////
        /// @brief Gets an entity value by its key.
        /// @param key Represents the model entity key.
        /// @return Reference to the string entity selected by key.
        ////////////////////////////////////////////////////////////////////////////////////////////////
        virtual const std::string &getEntity(const std::string_view &key
        ) const = 0;

        ////////////////////////////////////////////////////////////////////////////////////////////////
        /// @brief Updates an entity value by its key.
        /// @param key Represents the model entity key.
        /// @param data Represents the new value for the entity.
        /// @return true if the entity was updated, false if the key does not
        /// exist.
        ////////////////////////////////////////////////////////////////////////////////////////////////
        virtual bool
        update(const std::string_view &key, const std::string_view &data) = 0;

        ////////////////////////////////////////////////////////////////////////////////////////////////
        /// @brief Gets all model entities.
        /// @return Constant reference to the map of strings {key: data}.
        ////////////////////////////////////////////////////////////////////////////////////////////////
        virtual const Entities &get() const = 0;

        ////////////////////////////////////////////////////////////////////////////////////////////////
        /// @brief Gets a copy of all model entries.
        /// @return A new map containing all model entries {key: data}.
        ////////////////////////////////////////////////////////////////////////////////////////////////
        virtual Entities getAllEntries() const = 0;

        ////////////////////////////////////////////////////////////////////////////////////////////////
        /// @brief Clears all entities from the model.
        ////////////////////////////////////////////////////////////////////////////////////////////////
        virtual void clear() = 0;

        ////////////////////////////////////////////////////////////////////////////////////////////////
        /// @brief Gets the state of a specific channel.
        /// @param index The index of the channel.
        /// @return The ChannelState representation of the channel status.
        ////////////////////////////////////////////////////////////////////////////////////////////////
        virtual ChannelState getChannelState(size_t index) const = 0;

        ////////////////////////////////////////////////////////////////////////////////////////////////
        /// @brief Sets the state of a specific channel.
        /// @param index The index of the channel.
        /// @param state The new ChannelState value.
        ////////////////////////////////////////////////////////////////////////////////////////////////
        virtual void
        setChannelState(size_t index, const ChannelState &state) = 0;

        ////////////////////////////////////////////////////////////////////////////////////////////////
        /// @brief Converts a ModelControlKey enum value to its string
        /// representation.
        /// @param key Represents the ModelControlKey enum value.
        /// @return A string_view containing the key name.
        ////////////////////////////////////////////////////////////////////////////////////////////////
        virtual std::string_view toString(ModelControlKey key) const = 0;

        ////////////////////////////////////////////////////////////////////////////////////////////////
        /// @brief Converts a ModelLogKey enum value to its string
        /// representation.
        /// @param key Represents the ModelLogKey enum value.
        /// @return A string_view containing the key name.
        ////////////////////////////////////////////////////////////////////////////////////////////////
        virtual std::string_view toString(ModelLogKey key) const = 0;

        ////////////////////////////////////////////////////////////////////////////////////////////////
        /// @brief Converts a ModelSerialKey enum value to its string
        /// representation.
        /// @param key Represents the ModelSerialKey enum value.
        /// @return A string_view containing the key name.
        ////////////////////////////////////////////////////////////////////////////////////////////////
        virtual std::string_view toString(ModelSerialKey key) const = 0;

        ////////////////////////////////////////////////////////////////////////////////////////////////
        /// @brief Converts a ModelGeneralKey enum value to its string
        /// representation.
        /// @param key Represents the ModelGeneralKey enum value.
        /// @return A string_view containing the key name.
        ////////////////////////////////////////////////////////////////////////////////////////////////
        virtual std::string_view toString(ModelGeneralKey key) const = 0;

        ////////////////////////////////////////////////////////////////////////////////////////////////
        /// @brief Converts a ModelBleKey enum value to its string
        /// representation.
        /// @param key Represents the ModelBleKey enum value.
        /// @return A string_view containing the key name.
        ////////////////////////////////////////////////////////////////////////////////////////////////
        virtual std::string_view toString(ModelBleKey key) const = 0;

        ////////////////////////////////////////////////////////////////////////////////////////////////
        /// @brief Gets the signal emitted when model data changes.
        /// @return A sigc::signal instance.
        ////////////////////////////////////////////////////////////////////////////////////////////////
        virtual sigc::signal<void()> signal_changed() const = 0;

        ////////////////////////////////////////////////////////////////////////////////////////////////
        /// @brief Triggers notification of model changes to observers.
        ////////////////////////////////////////////////////////////////////////////////////////////////
        virtual void emit_changed() const = 0;

        ////////////////////////////////////////////////////////////////////////////////////////////////
        /// @brief Polymorphic deep copy of the model.
        /// @return A unique_ptr containing the cloned IModel.
        ////////////////////////////////////////////////////////////////////////////////////////////////
        virtual std::unique_ptr<IModel> clone() const = 0;
    };
} // namespace Electux::App::Model
